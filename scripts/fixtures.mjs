import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
await mkdir("public/fixtures", { recursive: true });
const label = (batch, expiry) =>
  `<svg width="1400" height="1000" xmlns="http://www.w3.org/2000/svg"><rect width="1400" height="1000" fill="#f5f2e8"/><rect x="40" y="40" width="1320" height="920" rx="20" fill="white" stroke="#164e50" stroke-width="5"/><rect x="40" y="40" width="1320" height="135" fill="#123c40"/><text x="100" y="125" fill="white" font-family="Arial" font-size="48" font-weight="bold">ASTER / EVERYDAY GOODNESS</text><g font-family="Arial" fill="#152b35" font-size="40"><text x="100" y="260">PRODUCT: Aster Oat Drink</text><text x="100" y="330">VARIANT: Original</text><text x="100" y="400">BATCH: ${batch}</text><text x="100" y="470">MFG: 2026-10-01</text><text x="100" y="540">EXP: ${expiry}</text><text x="100" y="610">NET: 250 ml</text><text x="100" y="720">Store in a cool dry place</text><text x="100" y="785">Shake well before use</text></g><text x="100" y="900" font-family="Arial" font-size="23" fill="#526370">SYNTHETIC TEST FIXTURE / FICTIONAL PRODUCT / NOT FOR SALE</text></svg>`;
for (const [name, batch, expiry] of [
  ["correct", "BV-2026-042", "2027-04-01"],
  ["wrong-batch", "BV-2026-099", "2027-04-01"],
  ["wrong-expiry", "BV-2026-042", "2027-06-01"],
])
  await sharp(Buffer.from(label(batch, expiry)))
    .png()
    .toFile(`public/fixtures/${name}.png`);
await sharp(Buffer.from(label("BV-2026-042", "2027-04-01")))
  .resize(210, 150)
  .blur(1.5)
  .png()
  .toFile("public/fixtures/ambiguous.png");
await writeFile(
  "public/fixtures/README.txt",
  "All images are synthetic fictional test labels, not real manufacturing validation. Generated by scripts/fixtures.mjs.",
);
const reference = Buffer.from(label("BV-2026-042", "2027-04-01"));
const patch = await sharp({
  create: { width: 500, height: 80, channels: 3, background: "white" },
})
  .png()
  .toBuffer();
await sharp(reference)
  .composite([{ input: patch, left: 90, top: 675 }])
  .png()
  .toFile("public/fixtures/missing-print.png");
await sharp(reference)
  .rotate(12, { background: "white" })
  .resize(1400, 1000, { fit: "fill" })
  .png()
  .toFile("public/fixtures/rotated.png");
console.log("Generated six synthetic label images.");
